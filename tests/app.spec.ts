  await page.getByRole('button', { name: 'Fechar janela' }).click();
  await page.reload();
  await expect(page.locator('.metric.balance')).toContainText(/30,00/);
  await page.getByRole('tab', { name: 'Meus Dados e PIX' }).click();
  await page.getByLabel('Nome completo').fill(`Atendente ${info.project.name}`);
  await page.getByLabel('Tipo de chave PIX').selectOption('email');
  await page.getByLabel('Chave PIX', { exact: true }).fill(`${info.project.name}@example.com`);
  await page.getByLabel('Nome do titular da chave').fill(`Atendente ${info.project.name}`);
