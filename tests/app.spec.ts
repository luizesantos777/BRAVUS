test('administrador cria atendente, configura custos, troca e revoga o token', async ({ page }, info) => {
  await page.goto('/#/admin');
  await page.getByLabel('Chave administrativa').fill('fixture_browser_admin_012345678901234567890123456789');
  await page.getByRole('button', { name: 'Entrar na administração' }).click();
  await expect(page.getByRole('heading', { name: 'Visão administrativa' })).toBeVisible();
  await page.getByRole('button', { name: 'Novo atendente', exact: true }).click();
  const name = `Nova pessoa ${info.project.name}`;
  await page.getByLabel('Nome do atendente', { exact: true }).fill(name);
  await page.getByLabel('Comissão (%)').fill('12,5');
  const chosenToken = `fixture_owner_${info.project.name}_token_01234567890123456789`;
  await page.getByLabel('Token do atendente (opcional)').fill(chosenToken);
  await page.getByRole('button', { name: 'Criar atendente e token' }).click();
  const invite = page.getByLabel('Link privado do atendente');
  await expect(invite).toBeVisible();
  const oldToken = new URL(await invite.inputValue()).hash.split('/').at(-1)!;
  expect(oldToken).toBe(chosenToken);
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  const row = page.getByRole('row').filter({ has: page.getByText(name, { exact: true }) });
  await expect(row).toContainText('12.5%');
  const response = await page.request.get('/api/portal', { headers: { Authorization: `Bearer ${oldToken}` } });
  expect(response.status()).toBe(200);
  const id = (await response.json()).profile.id;
  await page.getByRole('button', { name: 'Taxas e custos' }).click();
  await page.getByLabel('Atendente', { exact: true }).selectOption(id);
  await expect(page.getByLabel('Custo ADS (R$)')).toBeEnabled();
  await page.getByLabel('Custo ADS (R$)').fill('5');
  await page.getByLabel('Taxa diária de saque (R$)').fill('2');
  await page.getByRole('button', { name: 'Salvar custos do dia' }).click();
  await expect(page.getByRole('status')).toContainText('Custos diários salvos');
  await page.getByRole('button', { name: 'Atendentes', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await row.getByRole('button', { name: 'Novo token' }).click();
  await expect(invite).toBeVisible();
  const nextToken = new URL(await invite.inputValue()).hash.split('/').at(-1)!;
  expect(nextToken).not.toBe(oldToken);
  expect((await page.request.get('/api/portal', { headers: { Authorization: `Bearer ${oldToken}` } })).status()).toBe(401);
  const next = await page.request.get('/api/portal', { headers: { Authorization: `Bearer ${nextToken}` } });
  expect((await next.json()).finance.availableCents).toBe(-700);
  await page.getByRole('button', { name: 'Fechar janela' }).click();
  page.once('dialog', dialog => dialog.accept());
  await row.getByRole('button', { name: 'Revogar', exact: true }).click();
  await expect(row).toContainText('Revogado');
  expect((await page.request.get('/api/portal', { headers: { Authorization: `Bearer ${nextToken}` } })).status()).toBe(401);
  await page.screenshot({ path: info.outputPath('administracao.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await page.evaluate(() => Object.keys(localStorage).filter(key => /admin|token/i.test(key)))).toEqual([]);
  await page.getByRole('button', { name: 'Sair', exact: true }).click();
  await expect(page.getByLabel('Chave administrativa')).toHaveValue('');
});

test('perfil BRAVUS: foto, PIX, alerta personalizado e notificações no aparelho', async ({ page, context }, info) => {
  await context.grantPermissions(['notifications']);
  await page.goto('/?aba=perfil');
  await expect(page.getByRole('heading', { name: 'Dados Pessoais, Chave PIX & Notificações Push' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'EXTRATO FINANCEIRO & COMISSÕES' })).toHaveCount(0);
  await page.screenshot({ path: info.outputPath('perfil-bravus.png'), fullPage: true });
  const name = `Perfil ${info.project.name}`;
  await page.getByLabel('Seu Nome / Apelido no Painel').fill(name);
  await page.getByLabel('Texto do alerta de venda').fill('{nome}: {qtd} venda(s), total {valor}!');
  await expect(page.getByLabel('Prévia do alerta de venda')).toContainText(`${name}: 1 venda(s), total R$`);
  const avatar = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 64; canvas.height = 64;
    const context = canvas.getContext('2d')!; context.fillStyle = '#086b3b'; context.fillRect(0, 0, 64, 64);
    context.fillStyle = '#e2b640'; context.fillRect(16, 16, 32, 32);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  await page.getByLabel('Foto de perfil', { exact: true }).setInputFiles({ name: 'perfil.png', mimeType: 'image/png', buffer: Buffer.from(avatar, 'base64') });
  await expect(page.getByRole('button', { name: 'Remover foto' })).toBeVisible();
  await page.getByLabel('Chave PIX para Pagamento').fill('perfil@example.com');
  await expect(page.getByLabel('Tipo da chave PIX')).toHaveValue('email');
  await page.getByLabel('Nome Completo do Titular da Chave PIX').fill(name);
  await page.getByRole('button', { name: 'Salvar Alterações' }).click();
  await expect(page.getByRole('status')).toContainText('Alterações salvas');
  await page.reload();
  await expect(page.getByLabel('Seu Nome / Apelido no Painel')).toHaveValue(name);
  await expect(page.getByLabel('Texto do alerta de venda')).toHaveValue('{nome}: {qtd} venda(s), total {valor}!');
  await expect(page.getByRole('img', { name: `Foto de ${name}`, exact: true })).toHaveCount(2);
  await page.getByRole('button', { name: 'Ativar Notificações no Celular' }).click();
  await expect(page.locator('.notification-badge')).toHaveText('Ativado');
  await page.getByRole('tab', { name: 'Lançar Vendas' }).click();
  await page.getByLabel('Valor bruto venda 1', { exact: true }).fill('100');
  await page.getByLabel('Checkout venda 1', { exact: true }).selectOption('pix');
  await page.getByLabel('Print da venda 1', { exact: true }).setInputFiles(image);
  await page.getByRole('button', { name: 'Salvar e Enviar Vendas' }).click();
  await expect(page.getByRole('status')).toContainText(`${name}: 1 venda(s), total R$`);
  await expect.poll(() => page.evaluate(async () => (await (await navigator.serviceWorker.ready).getNotifications()).map(notification => notification.body).join('\n'))).toContain(`${name}: 1 venda(s), total R$`);
  await page.getByRole('tab', { name: 'Ranking', exact: true }).click();
  await expect(page.locator('.ranking-row.mine img')).toBeVisible();
  await page.getByRole('tab', { name: 'Meus Dados e PIX' }).click();
  await page.getByRole('button', { name: 'Desativar neste aparelho' }).click();
  await expect(page.locator('.notification-badge')).toHaveText('Desativado');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
